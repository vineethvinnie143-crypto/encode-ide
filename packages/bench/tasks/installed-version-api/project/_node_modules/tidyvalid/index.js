const RULES = Symbol('rules')

function rule(rules) {
  return {
    [RULES]: rules,
    min(length, message = `must be at least ${length} characters`) {
      return rule([...rules, (value) => (value.length >= length ? null : message)])
    },
    email(message = 'must be an email address') {
      return rule([...rules, (value) => (/^[^\s@]+@[^\s@]+$/.test(value) ? null : message)])
    },
  }
}

export function string() {
  return rule([(value) => (typeof value === 'string' ? null : 'must be text')])
}

export function schema(shape) {
  return {
    check(value) {
      const issues = []
      const input = value && typeof value === 'object' ? value : {}
      for (const [path, field] of Object.entries(shape)) {
        for (const test of field[RULES]) {
          const message = test(input[path])
          if (message) {
            issues.push({ path, message })
            break
          }
        }
      }
      return issues.length ? { ok: false, issues } : { ok: true, value: input }
    },
  }
}
