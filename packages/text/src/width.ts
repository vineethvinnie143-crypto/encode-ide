const ZERO_WIDTH = /^[\p{Mn}\p{Me}\p{Cf}]$/u

function inRanges(ranges: readonly number[], code: number): boolean {
  let lo = 0
  let hi = ranges.length / 2 - 1
  while (lo <= hi) {
    const mid = (lo + hi) >> 1
    if (code < ranges[mid * 2]) hi = mid - 1
    else if (code > ranges[mid * 2 + 1]) lo = mid + 1
    else return true
  }
  return false
}

/** Cells taken by one code point. Control characters take none. */
export function codePointWidth(code: number): 0 | 1 | 2 {
  if (code < 0x7f) return code >= 0x20 ? 1 : 0
  if (code < 0xa0) return 0
  if (code < 0x300) return code === 0xad ? 0 : 1
  if (code === 0x200b || (code >= 0x1160 && code <= 0x11ff)) return 0
  if (inRanges(WIDE, code)) return 2
  if (ZERO_WIDTH.test(String.fromCodePoint(code))) return 0
  return 1
}

/** Cells taken by a string, with tabs counted as `tabSize`-aligned stops from `startColumn`. */
export function stringWidth(text: string, tabSize = 4, startColumn = 0): number {
  let column = startColumn
  for (let index = 0; index < text.length; index++) {
    const code = text.charCodeAt(index)
    if (code === 9) {
      column += tabSize - (column % tabSize)
    } else if (code < 0x7f) {
      if (code >= 0x20) column++
    } else {
      const point = text.codePointAt(index)!
      if (point > 0xffff) index++
      column += codePointWidth(point)
    }
  }
  return column - startColumn
}
